// Append projection across OMP's three system-prompt layouts.
//
// OMP v18.2.8 `packages/coding-agent/src/system-prompt.ts` picks block 0 and
// renders the PROJECT footer from the SAME flag:
//
//   const selectedTemplate = resolvedCustomPrompt
//       ? customSystemPromptTemplate
//       : (resolvedSystemPromptTemplate ?? systemPromptTemplate);
//   ...
//   prompt.render(projectPromptTemplate,
//       resolvedCustomPrompt ? { ...data, contextFiles: [], appendPrompt: "" } : data)
//
// `resolvedCustomPrompt` is set only by the literal routes (`SYSTEM.md`,
// `--system-prompt`). A template route (`SYSTEM_TEMPLATE.md`,
// `--system-prompt-template`) leaves it undefined, so block 0 is the user's
// rendered template AND the PROJECT footer still carries the real
// `contextFiles` + `appendPrompt`. Upstream docs state the same:
// "With SYSTEM_TEMPLATE.md (or --system-prompt-template), append text remains
// generated by the normal project/footer route."
//
// The bridge used to read append from the PROJECT tail only when block 0 was
// NOT portable custom text. A rendered template is portable custom text, so the
// user's append was silently dropped on that route.

import assert from "node:assert/strict";
import test from "node:test";
import { deriveCaptureInput, projectPromptCapture, PromptCaptures } from "../src/prompt-capture.ts";
import { customPromptBlock, defaultHarnessBlock, projectBlock } from "./fixtures/omp-system-prompts.mjs";

const count = (haystack, needle) => haystack.split(needle).length - 1;

function project(assembled) {
	const key = assembled.join("\n\n");
	const captures = new PromptCaptures();
	captures.record(key, deriveCaptureInput(assembled));
	const projected = projectPromptCapture(captures.resolve(key));
	assert.ok(projected, "expected a projected append");
	return projected;
}

// --- C. SYSTEM_TEMPLATE.md / --system-prompt-template ----------------------

test("SYSTEM_TEMPLATE: the PROJECT append survives alongside the rendered template", () => {
	// `TEMPLATE-SENTINEL` is deliberately not a substring of the append sentinel,
	// so the occurrence counts below distinguish the two blocks.
	const template = "TEMPLATE-SENTINEL: rendered by the user's SYSTEM_TEMPLATE.md";
	const assembled = [
		template,
		projectBlock({
			contextFiles: [{ path: "/repo/AGENTS.md", content: "TEMPLATE-CONTEXT-SENTINEL" }],
			append: "TEMPLATE-APPEND-SENTINEL",
		}),
	];

	const input = deriveCaptureInput(assembled);
	assert.ok(input.custom?.includes("TEMPLATE-SENTINEL"), "the rendered template must stay portable custom text");
	assert.equal(input.append, "TEMPLATE-APPEND-SENTINEL", "the PROJECT append must be captured on the template route");

	const projected = project(assembled);
	assert.equal(count(projected, template), 1);
	assert.equal(count(projected, "TEMPLATE-APPEND-SENTINEL"), 1);
	assert.equal(count(projected, "TEMPLATE-CONTEXT-SENTINEL"), 1);
});

test("SYSTEM_TEMPLATE without an append does not manufacture one", () => {
	const assembled = [
		"TEMPLATE-ONLY-SENTINEL: no append configured",
		projectBlock({ contextFiles: [{ path: "/repo/AGENTS.md", content: "CONTEXT-NO-APPEND" }] }),
	];

	const input = deriveCaptureInput(assembled);
	assert.equal(input.append, undefined, "an empty PROJECT tail must not become an append");

	const projected = project(assembled);
	assert.equal(count(projected, "TEMPLATE-ONLY-SENTINEL"), 1);
	assert.equal(count(projected, "CONTEXT-NO-APPEND"), 1);
});

test("SYSTEM_TEMPLATE that renders dynamic OMP values keeps its rendered bytes", () => {
	// A template MAY reference `skills`/`rules` itself. Those rendered bytes are
	// user-authored output, not generated harness machinery the bridge re-renders.
	const assembled = [
		[
			"TEMPLATE-DYNAMIC-SENTINEL",
			"House rules for this repo:",
			"<rules>",
			'<rule name="house">TEMPLATE-RULE-SENTINEL</rule>',
			"</rules>",
		].join("\n"),
		projectBlock({ append: "APPEND-DYNAMIC-SENTINEL" }),
	];

	const input = deriveCaptureInput(assembled);
	assert.equal(input.rules?.length ?? 0, 0, "rule extraction stays scoped to the generated default harness");
	assert.ok(input.custom?.includes("TEMPLATE-RULE-SENTINEL"));

	const projected = project(assembled);
	assert.equal(count(projected, "TEMPLATE-DYNAMIC-SENTINEL"), 1);
	assert.equal(count(projected, "TEMPLATE-RULE-SENTINEL"), 1);
	assert.equal(count(projected, "APPEND-DYNAMIC-SENTINEL"), 1);
});

test("a template that intentionally repeats the append text keeps both copies", () => {
	// Upstream docs say a template SHOULD NOT render `appendPrompt` itself because
	// the footer already does — but a user MAY. OMP then assembles two copies on
	// purpose. The bridge preserves OMP's structure; it never content-dedupes.
	const append = "DOUBLED-APPEND-SENTINEL: emitted twice on purpose";
	const assembled = [`TEMPLATE-DOUBLING-SENTINEL\n\n${append}`, projectBlock({ append })];

	const projected = project(assembled);
	assert.equal(count(projected, "TEMPLATE-DOUBLING-SENTINEL"), 1);
	assert.equal(count(projected, append), 2, "OMP emitted the append twice; the bridge must not guess otherwise");
});

// --- B. plain SYSTEM.md / --system-prompt ----------------------------------

test("plain SYSTEM.md: the append rides inside block 0 and is never duplicated", () => {
	// OMP renders this footer with `contextFiles: []` and `appendPrompt: ""`, so
	// the PROJECT tail is genuinely empty and the extractor finds nothing there.
	const assembled = [
		customPromptBlock({
			custom: "CUSTOM-SENTINEL: the user's SYSTEM.md",
			append: "APPEND-PLAIN-SENTINEL",
			contextFiles: [{ path: "/repo/AGENTS.md", content: "PLAIN-CONTEXT-SENTINEL" }],
			skills: [{ name: "bridge", description: "PLAIN-SKILL-SENTINEL" }],
		}),
		projectBlock(),
	];

	const input = deriveCaptureInput(assembled);
	assert.equal(input.append, undefined, "the plain-custom footer carries no append to extract");
	assert.ok(input.custom?.includes("APPEND-PLAIN-SENTINEL"), "the append stays inside the portable custom block");

	const projected = project(assembled);
	assert.equal(count(projected, "CUSTOM-SENTINEL"), 1);
	assert.equal(count(projected, "APPEND-PLAIN-SENTINEL"), 1);
	assert.equal(count(projected, "PLAIN-CONTEXT-SENTINEL"), 1);
	assert.equal(count(projected, "PLAIN-SKILL-SENTINEL"), 1);
});

test("plain SYSTEM.md whose text merely resembles a footer tail stays single-copy", () => {
	// Defence in depth for the removed `customPrompt ? undefined` guard: even a
	// SYSTEM.md that quotes the generated `</critical>` marker must not have text
	// lifted out of block 0 and re-projected as a second append.
	const assembled = [
		customPromptBlock({
			custom: ["CUSTOM-QUOTING-SENTINEL", "<critical>", "- quoted policy", "</critical>", "TRAILING-CUSTOM-SENTINEL"].join(
				"\n",
			),
			append: "APPEND-QUOTED-SENTINEL",
		}),
		projectBlock(),
	];

	const projected = project(assembled);
	assert.equal(count(projected, "CUSTOM-QUOTING-SENTINEL"), 1);
	assert.equal(count(projected, "TRAILING-CUSTOM-SENTINEL"), 1);
	assert.equal(count(projected, "APPEND-QUOTED-SENTINEL"), 1);
});

test("a SYSTEM.md that impersonates the generated footer cannot inject an append", () => {
	// Sharper version of the case above, and the one the removed guard used to
	// mask: a SYSTEM.md that both opens with a `PROJECT` heading and quotes
	// project-prompt.md's generated <critical> block would shadow the real
	// footer, and its own trailing text would be lifted out of block 0 and
	// projected a second time. Upstream never places the footer at index 0, so
	// footer lookup skips block 0 and demands the generated marker.
	const spoof = [
		"PROJECT",
		"",
		"House notes for this repo.",
		"",
		"<critical>",
		"- Each response MUST advance the task; completion only stopping condition.",
		"</critical>",
		"TRAILING-BLOCK0-SENTINEL",
	].join("\n");
	const assembled = [customPromptBlock({ custom: spoof, append: "APPEND-SPOOF-SENTINEL" }), projectBlock()];

	const input = deriveCaptureInput(assembled);
	assert.equal(input.append, undefined, "block 0 text must never be lifted out as the PROJECT append");

	const projected = project(assembled);
	assert.equal(count(projected, "TRAILING-BLOCK0-SENTINEL"), 1);
	assert.equal(count(projected, "APPEND-SPOOF-SENTINEL"), 1);
});

test("the real footer is found wherever OMP places it in the array", () => {
	// v18.2.8 `system-prompt.ts` builds the array as `[rendered]`, pushes the
	// computer-safety block BEFORE the footer when the computer tool is enabled,
	// and pushes active-repo context AFTER it. The footer is therefore not at a
	// fixed index — only its never-being-index-0 is guaranteed — so the scan must
	// find it with generated blocks on either side.
	const assembled = [
		"TEMPLATE-SURROUNDED-SENTINEL",
		"<computer-safety>\ngenerated safety guidance\n</computer-safety>",
		projectBlock({ append: "APPEND-SURROUNDED-SENTINEL" }),
		"<active-repo-context>\ngenerated nested-repo context\n</active-repo-context>",
	];

	assert.equal(deriveCaptureInput(assembled).append, "APPEND-SURROUNDED-SENTINEL");
	assert.equal(count(project(assembled), "APPEND-SURROUNDED-SENTINEL"), 1);
});

// --- A. default bundled harness --------------------------------------------

test("default harness: the PROJECT append still projects exactly once", () => {
	const assembled = [
		defaultHarnessBlock({ generation: "18.2.8" }),
		projectBlock({
			contextFiles: [{ path: "/repo/AGENTS.md", content: "DEFAULT-CONTEXT-SENTINEL" }],
			append: "APPEND-DEFAULT-SENTINEL",
		}),
	];

	const input = deriveCaptureInput(assembled);
	assert.equal(input.custom, undefined, "the generated harness must not become custom content");
	assert.equal(input.append, "APPEND-DEFAULT-SENTINEL");

	const projected = project(assembled);
	assert.equal(count(projected, "APPEND-DEFAULT-SENTINEL"), 1);
	assert.equal(count(projected, "DEFAULT-CONTEXT-SENTINEL"), 1);
});

test("default harness without an append projects none", () => {
	const assembled = [
		defaultHarnessBlock({ generation: "18.2.8" }),
		projectBlock({ contextFiles: [{ path: "/repo/AGENTS.md", content: "DEFAULT-ONLY-CONTEXT" }] }),
	];

	assert.equal(deriveCaptureInput(assembled).append, undefined);
	assert.equal(count(project(assembled), "DEFAULT-ONLY-CONTEXT"), 1);
});
